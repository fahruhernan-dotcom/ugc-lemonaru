"""Domain data models for Velora AI."""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import uuid
from pydantic import BaseModel, Field, field_validator


class Product(BaseModel):
    """Canonical representation of an affiliate fashion product."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    product_id: str
    name: str
    category: str = "fashion"
    price_idr: float
    commission_rate: float
    commission_amount_idr: float = 0.0
    sales_count: int = 0
    rating: Optional[float] = None
    shop_name: str
    stock_available: int = 0
    affiliate_url: Optional[str] = None
    image_urls: List[str] = Field(default_factory=list)
    status: str = "active"
    raw_payload: Dict[str, Any] = Field(default_factory=dict)
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @field_validator("commission_amount_idr", mode="before")
    @classmethod
    def calculate_commission_amount(cls, v, info):
        price = info.data.get("price_idr", 0.0)
        rate = info.data.get("commission_rate", 0.0)
        return round(price * rate, 2)


class ProductScore(BaseModel):
    """Deterministic 6D score and gate evaluation for an affiliate product."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    product_id: str
    commission_attractiveness: float
    commission_stability: float
    sales_velocity: float
    creator_reputation: float
    niche_fit: float
    content_adaptability: float
    final_score: float
    is_eligible: bool
    ineligibility_reasons: List[str] = Field(default_factory=list)
    score_breakdown: Dict[str, Any] = Field(default_factory=dict)
    scoring_version: str = "v1.0"
    evaluated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ShotItem(BaseModel):
    """A single storyboard scene in a vertical video brief."""
    scene_number: int
    time_range: str
    visual_description: str
    camera_movement: str
    spoken_script: str
    on_screen_text: str


class ContentBrief(BaseModel):
    """Structured content brief generated by Hermes for production."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    product_id: str
    product_score_id: Optional[str] = None
    hook_type: str
    hook_text: str
    script_body: str
    shot_list: List[ShotItem] = Field(default_factory=list)
    product_facts: List[str] = Field(default_factory=list)
    cta_text: str
    caption: str
    hashtags: List[str] = Field(default_factory=list)
    asset_requirements: Dict[str, Any] = Field(default_factory=dict)
    target_aspect_ratio: str = "9:16"
    estimated_duration_seconds: int = 35
    package_export_path: Optional[str] = None
    status: str = "draft"  # draft, ready_for_production, completed
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class WorkflowEvent(BaseModel):
    """Audit log entry for tracing operations."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    event_type: str
    aggregate_type: str
    aggregate_id: str
    payload: Dict[str, Any] = Field(default_factory=dict)
    actor: str = "hermes_orchestrator"
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ProductMedia(BaseModel):
    """Product photo reference, clean crop, or background-isolated cutout."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    product_id: str
    media_type: str = "catalog_image"  # catalog_image, clean_crop, chin_down, isolated_white_bg
    file_path: str
    storage_provider: str = "local_drive_d"
    public_url: Optional[str] = None
    dimensions: Dict[str, int] = Field(default_factory=lambda: {"width": 0, "height": 0})
    is_primary: bool = False
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class UgcGeneration(BaseModel):
    """Generated video render, audio track, prompt, and quality benchmark."""
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    brief_id: str
    product_id: str
    model_name: str = "google_flow_omni_flash_1.1"
    prompt_used: str
    reference_image_id: Optional[str] = None
    video_path: Optional[str] = None
    voiceover_path: Optional[str] = None
    duration_seconds: float = 10.0
    quality_score: float = 8.50  # e.g. 8.5/10 benchmark
    quality_notes: Optional[str] = None
    status: str = "draft"  # queued, rendering, completed, failed, approved
    package_path: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

